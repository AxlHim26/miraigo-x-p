import { useFocusEffect, useLocalSearchParams, type Href } from 'expo-router';
import { useCallback, useEffect, useRef, useState } from 'react';
import { ActivityIndicator, FlatList, StyleSheet, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { ThemedText } from '@/components/themed-text';
import { ThemedView } from '@/components/themed-view';
import { LearnerBack } from '@/components/ui/learner-detail';
import { LearnerControl } from '@/components/ui/learner-glass';
import { describeVoiceError } from '@/features/practice/services/voice-errors';
import { CaptionRow } from '@/features/youtube/components/caption-row';
import { YouTubePlayer, type YouTubePlayerHandle } from '@/features/youtube/components/youtube-player.native';
import { useLineRecorder } from '@/features/youtube/hooks/use-line-recorder';
import { useCaptions } from '@/features/youtube/hooks/use-youtube';
import { activeLineIndex, isVideoId } from '@/features/youtube/utils/youtube';
import type { CaptionLine } from '@/integrations/ai/ai-client';

export function YouTubeShadowingScreen() {
  const { videoId } = useLocalSearchParams<{ videoId: string }>();
  if (!videoId || !isVideoId(videoId)) {
    return (
      <ThemedView style={styles.center}>
        <ThemedText>Mã video không hợp lệ.</ThemedText>
        <LearnerBack href="/practice" label="Luyện tập" />
      </ThemedView>
    );
  }
  return <Shadowing key={videoId} videoId={videoId} />;
}

function Shadowing({ videoId }: { videoId: string }) {
  const insets = useSafeAreaInsets();
  const captions = useCaptions(videoId);
  const player = useRef<YouTubePlayerHandle>(null);
  const list = useRef<FlatList<CaptionLine>>(null);
  const recorder = useLineRecorder();
  const [active, setActive] = useState(-1);
  const [selected, setSelected] = useState(-1);
  const [playing, setPlaying] = useState(false);
  const [furigana, setFurigana] = useState(true);
  const [playerError, setPlayerError] = useState(false);
  const lines = captions.data?.lines;

  useFocusEffect(useCallback(() => () => player.current?.pause(), []));

  // Follow the video: keep the spoken line near the top while it plays.
  useEffect(() => {
    if (playing && active >= 0) list.current?.scrollToIndex({ index: active, viewPosition: 0.2, animated: true });
  }, [active, playing]);

  const onTime = useCallback((time: number) => {
    if (lines) setActive(activeLineIndex(lines, time));
  }, [lines]);

  const { start, stop, isRecording, busy } = recorder;
  const play = useCallback((index: number) => {
    const line = lines?.[index];
    if (!line || isRecording || busy) return;
    setSelected(index);
    setActive(index);
    player.current?.playSegment(line.start, line.end);
  }, [lines, isRecording, busy]);

  const record = useCallback((index: number) => {
    const line = lines?.[index];
    if (!line) return;
    player.current?.pause();
    void start(index, line.text);
  }, [lines, start]);

  return (
    <ThemedView style={styles.screen}>
      <View style={styles.toolbar}>
        <LearnerBack href={'/practice/youtube' as Href} label="Video" />
        <LearnerControl label="Furigana" selected={furigana} onPress={() => setFurigana((value) => !value)} />
      </View>
      <YouTubePlayer
        ref={player}
        videoId={videoId}
        onTime={onTime}
        onPlayingChange={setPlaying}
        onError={() => setPlayerError(true)}
      />
      {playerError && (
        <ThemedText style={styles.notice} accessibilityLiveRegion="polite">
          Video này không phát được trong app (chủ kênh có thể đã chặn nhúng).
        </ThemedText>
      )}
      {captions.isPending && <ActivityIndicator style={styles.notice} />}
      {captions.isError && (
        <View style={styles.notice}>
          <ThemedText>{describeVoiceError(captions.error) ?? 'Không tải được phụ đề. Kiểm tra máy chủ AI rồi thử lại.'}</ThemedText>
          <LearnerControl label="Thử lại" onPress={() => void captions.refetch()} />
        </View>
      )}
      {lines && (
        <FlatList
          ref={list}
          data={lines}
          keyExtractor={(line, index) => `${line.start}-${index}`}
          contentContainerStyle={[styles.list, { paddingBottom: insets.bottom + 24 }]}
          initialNumToRender={8}
          maxToRenderPerBatch={6}
          windowSize={5}
          onScrollToIndexFailed={({ index, averageItemLength }) =>
            list.current?.scrollToOffset({ offset: index * averageItemLength, animated: true })}
          ListHeaderComponent={captions.data?.isAutoGenerated ? (
            <ThemedText type="small" themeColor="textSecondary" style={styles.auto}>
              Phụ đề tự động của YouTube, có thể sai chữ.
            </ThemedText>
          ) : undefined}
          renderItem={({ item, index }) => (
            <CaptionRow
              line={item}
              index={index}
              active={index === active}
              selected={index === selected}
              showFurigana={furigana}
              score={recorder.scores[index]}
              isRecording={index === selected && isRecording}
              busy={index === selected && busy}
              message={index === selected ? recorder.message : ''}
              onPlay={play}
              onRecord={record}
              onStop={() => void stop()}
            />
          )}
        />
      )}
    </ThemedView>
  );
}

const styles = StyleSheet.create({
  screen: { flex: 1 },
  center: { flex: 1, alignItems: 'center', justifyContent: 'center', gap: 12 },
  toolbar: { flexDirection: 'row', justifyContent: 'space-between', paddingHorizontal: 12, paddingVertical: 8 },
  notice: { padding: 16, gap: 8 },
  list: { padding: 12 },
  auto: { marginBottom: 8 },
});
